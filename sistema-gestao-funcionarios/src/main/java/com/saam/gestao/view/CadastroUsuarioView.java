    private void alternarVisibilidade(javax.swing.JPasswordField campo, javax.swing.JToggleButton botao) {
        campo.setEchoChar(botao.isSelected() ? (char) 0 : echoCharPadrao);
    }

    private void configurarChecklistDeSenha() {
        txtSenha.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
            @Override
            public void insertUpdate(javax.swing.event.DocumentEvent e) {
                atualizarChecklist();
            }

            @Override
            public void removeUpdate(javax.swing.event.DocumentEvent e) {
                atualizarChecklist();
            }

            @Override
            public void changedUpdate(javax.swing.event.DocumentEvent e) {
                atualizarChecklist();
            }
        });
    }

    private void atualizarChecklist() {
        String senha = new String(txtSenha.getPassword());
        marcarRegra(lblRegraTamanho, com.saam.gestao.util.PasswordPolicy.temTamanhoMinimo(senha));
        marcarRegra(lblRegraMaiuscula, com.saam.gestao.util.PasswordPolicy.temMaiuscula(senha));
        marcarRegra(lblRegraMinuscula, com.saam.gestao.util.PasswordPolicy.temMinuscula(senha));
        marcarRegra(lblRegraNumero, com.saam.gestao.util.PasswordPolicy.temNumero(senha));
        marcarRegra(lblRegraEspecial, com.saam.gestao.util.PasswordPolicy.temCaractereEspecial(senha));
    }

    private void marcarRegra(javax.swing.JLabel label, boolean atendida) {
        label.setForeground(atendida ? COR_REGRA_OK : COR_REGRA_PENDENTE);
    }

