    private final com.saam.gestao.service.AuthService authService = new com.saam.gestao.service.AuthService();

    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String senha = new String(txtSenha.getPassword());
        String confirmacao = new String(txtConfirmarSenha.getPassword());

        if (!senha.equals(confirmacao)) {
            javax.swing.JOptionPane.showMessageDialog(this, "As senhas informadas não coincidem.",
                "Validação", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            authService.cadastrar(txtNome.getText(), txtEmail.getText(), senha);
            javax.swing.JOptionPane.showMessageDialog(this, "Cadastro realizado com sucesso! Faça login.",
                "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            new com.saam.gestao.view.LoginView().setVisible(true);
            this.dispose();
        } catch (com.saam.gestao.exception.ValidationException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                "Não foi possível cadastrar", javax.swing.JOptionPane.WARNING_MESSAGE);
        } catch (com.saam.gestao.exception.DatabaseException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                "Erro de conexão", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

